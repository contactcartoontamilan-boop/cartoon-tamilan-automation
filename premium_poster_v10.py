"""V10 premium original-story social poster (1080x1350 JPEG).

One source illustration is necessary: either your own website cover or a
genuinely generated image from configured ComfyUI. Typography is typeset with
Pillow RAQM (Tamil shaping), NOT generated by an image model.
"""
import hashlib
import json
import math
from pathlib import Path

from PIL import Image, ImageDraw, ImageEnhance, ImageFilter
from poster_generator import find_font, latin_font, font_at, lines_for, require_tamil_shaping

THEMES = {
    "royal": {"gold": (255, 204, 76), "ruby": (235, 47, 101), "glow": (172, 43, 237)},
    "crimson": {"gold": (255, 197, 74), "ruby": (245, 57, 58), "glow": (236, 42, 126)},
    "cosmic": {"gold": (239, 217, 128), "ruby": (88, 96, 237), "glow": (63, 138, 255)},
    "emerald": {"gold": (249, 212, 104), "ruby": (29, 154, 127), "glow": (18, 182, 173)},
}


def _fit_image(artwork, size=(1080, 1350)):
    """Fill artwork canvas with a deliberately top-biased crop."""
    with Image.open(artwork) as source:
        image = source.convert("RGB")
    w, h = size
    scale = max(w / image.width, h / image.height)
    resized = image.resize((math.ceil(image.width * scale),
                            math.ceil(image.height * scale)), Image.Resampling.LANCZOS)
    left = (resized.width - w) // 2
    top = int((resized.height - h) * .15)
    return resized.crop((left, top, left + w, top + h))


def _fade_artwork(base, start=545, end=830):
    """Fully mask lower source cover lettering. Upper lettering needs clean art."""
    w, h = base.size
    layer = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    pen = ImageDraw.Draw(layer)
    for y in range(start, min(end, h)):
        alpha = int(255 * ((y - start) / (end - start)) ** 0.8)
        pen.line((0, y, w, y), fill=(13, 7, 34, alpha))
    pen.rectangle((0, min(end, h), w, h), fill=(13, 7, 34, 255))
    return Image.alpha_composite(base.convert("RGBA"), layer)


def _sparkles(canvas, seed, color):
    w, _ = canvas.size
    rng = hashlib.sha256(str(seed).encode("utf-8")).digest()
    d = ImageDraw.Draw(canvas)
    # Deterministic accents, not random noise over the faces.
    for i in range(18):
        x = 27 + (rng[i] * 103 + i * 79) % (w - 55)
        y = 125 + ((rng[(i + 11) % 32] * 97 + i * 131) % 590)
        rad = (rng[i] % 3) + 2
        d.ellipse((x-rad, y-rad, x+rad, y+rad), fill=(*color, 160))
        if i % 5 == 0:
            d.line((x-10, y, x+10, y), fill=(*color, 125), width=2)
            d.line((x, y-10, x, y+10), fill=(*color, 125), width=2)


def _draw_gold_title(canvas, title, tamil_font_path):
    w, h = canvas.size
    d = ImageDraw.Draw(canvas)
    fit = None
    for size in range(90, 37, -2):
        font = font_at(tamil_font_path, size)
        try:
            rows = lines_for(d, title, font, 920)
        except ValueError:
            continue
        step = size + 21
        if 1 <= len(rows) <= 4 and len(rows) * step <= 276:
            fit = font, rows, step
            break
    if fit is None:
        raise ValueError("Tamil title too long: use a reviewed shorter story headline.")
    font, rows, step = fit
    first_y = 827 + (276 - len(rows) * step) // 2
    mask = Image.new("L", (w, h), 0)
    textdraw = ImageDraw.Draw(mask)
    y = first_y
    for row in rows:
        bounds = d.textbbox((0, 0), row, font=font)
        width = bounds[2] - bounds[0]
        x = (w - width) // 2 - bounds[0]
        d.text((x + 3, y + 6), row, font=font, fill=(8, 4, 24, 255),
               stroke_width=5, stroke_fill=(6, 4, 17, 255))
        textdraw.text((x, y), row, font=font, fill=255)
        y += step

    glow_alpha = mask.filter(ImageFilter.GaussianBlur(15)).point(
        lambda x: min(150, int(x * .75)))
    glow = Image.new("RGBA", (w, h), (249, 143, 42))
    glow.putalpha(glow_alpha)
    canvas = Image.alpha_composite(canvas, glow)

    gradient = Image.new("RGBA", (w, h))
    grad_draw = ImageDraw.Draw(gradient)
    for yy in range(h):
        # warm white highlights above, antique golden glow below
        t = min(1.0, max(0.0, (yy - first_y) / max(1, len(rows) * step)))
        col = (255, int(240 - t * 67), int(145 - t * 109), 255)
        grad_draw.line((0, yy, w, yy), fill=col)
    return Image.composite(gradient, canvas, mask)


def make_premium_poster(draft, artwork, destination, theme="royal", headline=None):
    require_tamil_shaping()
    if theme not in THEMES:
        raise ValueError("Supported themes: " + ", ".join(THEMES))
    item = json.loads(Path(draft).read_text(encoding="utf-8"))["item"]
    if item.get("kind") != "story":
        raise ValueError("Only original story posters are supported")
    title = str(headline or item.get("title") or "").strip()
    if not title:
        raise ValueError("Story title missing")
    art = Path(artwork)
    if not art.is_file():
        raise FileNotFoundError(str(art))
    gold = THEMES[theme]["gold"]
    ruby = THEMES[theme]["ruby"]
    glow = THEMES[theme]["glow"]
    w, h = 1080, 1350
    canvas = _fit_image(art, (w, h)).convert("RGBA")
    canvas = Image.alpha_composite(
        canvas, Image.new("RGBA", (w, h), (18, 7, 48, 42)))
    canvas = _fade_artwork(canvas)
    _sparkles(canvas, item.get("link") or title, gold)
    d = ImageDraw.Draw(canvas)
    en, ta = latin_font(), find_font()

    # Header: clean brand, genre-neutral so it doesn't invent story content.
    d.rounded_rectangle((28, 28, 1052, 114), radius=26,
                        fill=(7, 7, 28, 235), outline=(*gold, 170), width=3)
    d.text((65, 47), "Cartoon", font=font_at(en, 39), fill="#ffffff")
    d.text((240, 47), "Tamilan.in", font=font_at(en, 39), fill=(*gold, 255))
    d.rounded_rectangle((780, 132, 1032, 192), radius=22, fill=(*glow, 228),
                        outline=(*gold, 235), width=3)
    d.text((798, 149), "ORIGINAL STORY", font=font_at(en, 25), fill="#ffffff")

    # Gold engraved title section with visible breathing room.
    d.rounded_rectangle((45, 775, 1035, 1120), radius=32,
                        fill=(14, 7, 37, 242), outline=(*gold, 225), width=3)
    d.line((175, 807, 905, 807), fill=(*gold, 205), width=4)
    d.ellipse((528, 795, 552, 819), fill=(*gold, 255))
    canvas = _draw_gold_title(canvas, title, ta)
    d = ImageDraw.Draw(canvas)
    d.line((280, 1112, 800, 1112), fill=(*gold, 185), width=3)

    # Bright social CTA, purely graphical: link is in caption/profile.
    d.rounded_rectangle((103, 1142, 977, 1250), radius=42,
                        fill=(*ruby, 255), outline=(*gold, 255), width=7)
    # Minimal original book emblem.
    d.line([(157, 1182), (181, 1175), (200, 1184), (200, 1225)],
           fill="#ffffff", width=5, joint="curve")
    d.line([(200, 1184), (221, 1175), (245, 1182), (245, 1225)],
           fill="#ffffff", width=5, joint="curve")
    d.line([(157, 1182), (157, 1225), (200, 1236), (245, 1225), (245, 1182)],
           fill="#ffffff", width=4, joint="curve")
    d.text((293, 1168), "READ THE STORY  >>",
           font=font_at(en, 47), fill="#ffffff", stroke_width=1)
    footer = "TAMIL ORIGINAL STORIES  |  CARTOONTAMILAN.IN"
    footer_font = font_at(en, 25)
    bounds = d.textbbox((0, 0), footer, font=footer_font)
    d.text(((w - (bounds[2]-bounds[0])) // 2, 1291), footer,
           font=footer_font, fill="#e8dcff")

    output = Path(destination)
    output.parent.mkdir(parents=True, exist_ok=True)
    canvas.convert("RGB").save(output, "JPEG", quality=94, optimize=True)
    return output
